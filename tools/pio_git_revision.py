"""Generate Git provenance for the ESP32 image being compiled.

A compile-time generated header records the full Git HEAD SHA in the firmware,
not a manually updated version constant. The selected PlatformIO environment
has its own generated file, and incremental builds notice when HEAD changes.
"""
from pathlib import Path
import re
import subprocess

Import("env")

project = Path(env.subst("$PROJECT_DIR"))
build_dir = Path(env.subst("$BUILD_DIR"))
build_dir.mkdir(parents=True, exist_ok=True)

def git(*args):
    try:
        r = subprocess.run(["git", *args], cwd=str(project),
                           stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                           text=True, check=False)
        return r.stdout.strip() if r.returncode == 0 else None
    except OSError:
        return None

sha = git("rev-parse", "--verify", "HEAD")
if not sha or not re.fullmatch(r"[0-9a-fA-F]{40}", sha):
    # Building a source archive is supported, but clearly marked unverified.
    sha = "unknown"

# Include tracked and untracked source modifications, excluding ignored .pio.
dirty_output = git("status", "--porcelain", "--untracked-files=normal")
dirty = dirty_output is None or bool(dirty_output)

generated = build_dir / "ebtks_build_revision.h"
body = ('// Generated by PlatformIO pre-script; do not edit.\n'
        '#pragma once\n'
        f'#define EBTKS_BUILD_GIT_COMMIT "{sha}"\n'
        f'#define EBTKS_BUILD_GIT_DIRTY {int(dirty)}\n')
if not generated.exists() or generated.read_text(encoding="utf-8") != body:
    generated.write_text(body, encoding="utf-8")
env.Append(CPPPATH=[str(build_dir)])

print(f"EBTKS firmware Git revision: {sha} ({'dirty' if dirty else 'clean'})")
